import PacketProgress, { StatusPill } from "./PacketProgress";

function formatDate(value) {
  return value ? new Date(value).toLocaleString() : "Not available";
}

function downloadPDF(packet) {
  const win = window.open("", "_blank");
  if (!win) return;

  const html = `
    <!DOCTYPE html>
    <html>
    <head><title>${packet.title} - Details</title>
    <style>
      body { font-family: Arial, sans-serif; padding: 40px; color: #333; }
      h1 { color: #4f46e5; font-size: 24px; }
      .label { color: #888; font-size: 12px; text-transform: uppercase; margin-top: 20px; }
      .value { font-size: 16px; margin-top: 4px; }
      .grid { display: grid; grid-template-columns: 1fr 1fr; gap: 20px; }
      .section { margin-top: 30px; }
      hr { border: none; border-top: 1px solid #eee; margin: 20px 0; }
    </style></head>
    <body>
      <h1>${packet.title}</h1>
      <p style="color:#666">${packet.course || ""}</p>
      <hr/>
      <div class="grid">
        <div><div class="label">Status</div><div class="value">${packet.status}</div></div>
        <div><div class="label">Faculty</div><div class="value">${packet.facultyEmail || packet.submittedBy || "N/A"}</div></div>
        <div><div class="label">Submitted</div><div class="value">${formatDate(packet.createdAt)}</div></div>
        <div><div class="label">Last Updated</div><div class="value">${formatDate(packet.updatedAt)}</div></div>
      </div>
      <div class="section">
        <div class="label">Description</div>
        <div class="value">${packet.description || "No description added."}</div>
      </div>
      ${packet.remarks ? `<div class="section"><div class="label">Remarks</div><div class="value">${packet.remarks}</div></div>` : ""}
      <hr/>
      <p style="color:#aaa;font-size:12px;">Generated by PacketTrack - Course Packet Management System</p>
    </body></html>
  `;

  win.document.write(html);
  win.document.close();
  win.focus();
  win.print();
}

